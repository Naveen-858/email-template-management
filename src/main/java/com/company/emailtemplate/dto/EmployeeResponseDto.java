package com.company.emailtemplate.dto;

import java.time.LocalDate;
import java.time.LocalDateTime;

public class EmployeeResponseDto {
	private Long id;
	private String employeeCode;
	private String name;
	private String email;
	private String designation;
	private LocalDate dateOfJoining;
	private Integer previousExperienceMonths;
	private String status;
	private LocalDateTime createdAt;

	public Long getId() {
		return id;
	}

	public void setId(Long id) {
		this.id = id;
	}

	public String getEmployeeCode() {
		return employeeCode;
	}

	public void setEmployeeCode(String employeeCode) {
		this.employeeCode = employeeCode;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getEmail() {
		return email;
	}

	public void setEmail(String email) {
		this.email = email;
	}

	public String getDesignation() {
		return designation;
	}

	public void setDesignation(String designation) {
		this.designation = designation;
	}

	public LocalDate getDateOfJoining() {
		return dateOfJoining;
	}

	public void setDateOfJoining(LocalDate dateOfJoining) {
		this.dateOfJoining = dateOfJoining;
	}

	public Integer getPreviousExperienceMonths() {
		return previousExperienceMonths;
	}

	public void setPreviousExperienceMonths(Integer previousExperienceMonths) {
		this.previousExperienceMonths = previousExperienceMonths;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public LocalDateTime getCreatedAt() {
		return createdAt;
	}

	public void setCreatedAt(LocalDateTime createdAt) {
		this.createdAt = createdAt;
	}

}
